#!/usr/bin/env bash
# install.sh — install or update the shared toolchains in /opt/tooling (README.md).
# Run on the host, as root:  sudo tooling/install.sh
# TOOLING_PREFIX=<dir> installs elsewhere, as any user (for testing).
set -euo pipefail

MISE_VERSION=v2026.9.5

here=$(cd "$(dirname "$0")" && pwd)
prefix=${TOOLING_PREFIX:-/opt/tooling}
# mise download/metadata cache, shared with lock.sh so re-runs skip re-fetching.
cache=${TOOLING_MISE_CACHE:-/opt/mise/cache}
if [[ -z ${TOOLING_PREFIX:-} && $(id -u) -ne 0 ]]; then
    echo "install.sh: run as root (sudo): /opt/tooling must not be writable by the user" >&2
    exit 1
fi
case $(uname -m) in
    x86_64) arch=x64 ;;
    aarch64) arch=arm64 ;;
    *) echo "install.sh: unsupported arch $(uname -m)" >&2; exit 1 ;;
esac

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
umask 022
mkdir -p "$prefix/bin" "$prefix/mise"

# mise itself: pinned, checksum-verified, kept off PATH (only this script runs it).
mise="$prefix/mise/mise-$MISE_VERSION"
if [[ ! -x $mise ]]; then
    asset=mise-$MISE_VERSION-linux-$arch-musl
    base=https://github.com/jdx/mise/releases/download/$MISE_VERSION
    curl -fsSL -o "$tmp/$asset" "$base/$asset"
    curl -fsSL -o "$tmp/SHASUMS256.txt" "$base/SHASUMS256.txt"
    (cd "$tmp" && grep -E " (\./)?$asset\$" SHASUMS256.txt | sed 's# \./# #' | sha256sum -c --quiet)
    install -m 0755 "$tmp/$asset" "$mise"
fi

install -m 0644 "$here/mise.toml" "$here/mise.lock" "$here/README.md" "$here/env.sh" "$prefix/"
rm -rf "$prefix/env"
install -d -m 0755 "$prefix/env"
install -m 0644 "$here"/env/*.sh "$prefix/env/"

# The tools, exactly as mise.toml + mise.lock pin them. Locked mode refuses any
# artifact the lockfile doesn't cover; rustup verifies its own downloads.
export MISE_DATA_DIR=$prefix/mise MISE_STATE_DIR=$prefix/mise/state \
    MISE_CONFIG_DIR=$prefix/mise/config MISE_GLOBAL_CONFIG_FILE=$prefix/mise/config/none.toml \
    MISE_CACHE_DIR=$cache MISE_RUSTUP_HOME=$prefix/rustup MISE_CARGO_HOME=$prefix/cargo \
    MISE_TRUSTED_CONFIG_PATHS=$prefix MISE_YES=1 MISE_LOCKED=1
(cd "$prefix" && "$mise" install)
# Under sudo, hand the shared cache back to its parent's owner, so lock.sh (any
# user) can still write it. Only metadata lives there; artifacts are checksummed.
if [[ $(id -u) -eq 0 ]]; then
    chown -R --no-dereference --reference="$(dirname "$cache")" "$cache"
fi

# One PATH entry for host and container: every executable each tool exposes
# (`mise bin-paths`) and every rustup proxy gets a wrapper in bin/. New tools need
# no change here.
#
# Wrappers, not symlinks: a tool whose launcher locates its own files relative to
# $0 (node's bin/npm -> ../lib/node_modules/npm) would resolve them against bin/
# and fail. `exec <real path>` keeps $0 inside the tool's own prefix, and leaves
# the basename intact for argv0 dispatch (rustup's cargo/rustc proxies).
rm -rf "$prefix/bin"
install -d -m 0755 "$prefix/bin"
wrap() {
    printf '#!/bin/sh\n# generated by tooling/install.sh\nexec "%s" "$@"\n' "$1" \
        > "$prefix/bin/${1##*/}"
    chmod 0755 "$prefix/bin/${1##*/}"
}
while IFS= read -r d; do
    for b in "$d"/*; do
        [[ -f $b && -x $b ]] || continue
        # npm's package/bin ships its Windows launchers and JS entry points
        # alongside the real commands, all executable; conda's clang exposes its
        # target .cfg files (read by clang from its own dir, not commands).
        case ${b##*/} in *.cmd | *.ps1 | *.bat | *.js | *.cfg) continue ;; esac
        wrap "$b"
    done
done < <(cd "$prefix" && "$mise" bin-paths)
for p in "$prefix"/cargo/bin/*; do
    wrap "$p"
done

# clang/clang++ from the one clangxx env (mise exposes only clang++ from it), run with our
# config instead of conda's: conda's puts the env's own include/ ahead of the sysroot, and its
# GNU libiconv iconv.h renames iconv_open, which glibc lacks (vcpkg libxml2 fails on it).
# Kept: sysroot (glibc 2.34) and the env's lib/ on the link path and RPATH (libstdc++ 16).
cxx=$(cd "$prefix" && "$mise" where conda:clangxx)
install -d -m 0755 "$prefix/config"
cat > "$prefix/config/clang.cfg" <<EOF
# generated by tooling/install.sh: replaces conda's default config (README.md)
--sysroot=$cxx/x86_64-conda-linux-gnu/sysroot
\$-Wl,-L,$cxx/lib
\$-Wl,-rpath,$cxx/lib
\$-Wl,-rpath-link,$cxx/lib
EOF
chmod 0644 "$prefix/config/clang.cfg"
for b in clang clang++ clang-cpp; do
    printf '#!/bin/sh\n# generated by tooling/install.sh\nexec "%s" --no-default-config --config="%s" "$@"\n' \
        "$cxx/bin/$b" "$prefix/config/clang.cfg" > "$prefix/bin/$b"
    chmod 0755 "$prefix/bin/$b"
done

# Our own scripts (bin/): copied, not wrapped, so they keep working when the repo checkout moves.
install -m 0755 "$here"/bin/* "$prefix/bin/"

# Verify through env.sh itself, as both sides will use it.
(
    TOOLING_ROOT=$prefix
    . "$prefix/env.sh"
    rustc --version; cargo --version; uv --version; sccache --version; go version
    clang --version | head -1; clang++ --version | head -1
)
